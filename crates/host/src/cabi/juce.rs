//! The JUCE adapter's build settings for one plugin, as CMake.

use std::fmt::Write as _;
use std::ops::RangeInclusive;

use crate::{Category, Plugin};

/// The VST3 id JUCE's wrapper gives the bypass parameter it adds itself
/// (`'byps'`), and the one it gives a program list (`'prst'`).
const JUCE_RESERVED_IDS: [(RangeInclusive<u32>, &str); 2] = [
    (0x6279_7073..=0x6279_7073, "JUCE's bypass"),
    (0x7072_7374..=0x7072_7374, "JUCE's program list"),
];

/// The VST3 ids of the parameters JUCE's wrapper adds for a plugin that
/// takes MIDI input, one for each of 130 controllers (pressure and pitch
/// bend among them) on each of 16 channels, from `'mcm\0'` on. JUCE adds
/// them unless `JUCE_VST3_EMULATE_MIDI_CC_WITH_PARAMETERS` is 0.
const JUCE_MIDI_CONTROLLER_IDS: RangeInclusive<u32> = 0x6d63_6d00..=0x6d63_6d00 + 16 * 130 - 1;

/// Returns the settings `seam_add_juce_plugin` (`adapters/juce/SeamJuce.cmake`)
/// reads for `P`, everything JUCE must know at build time.
///
/// They come from [`Plugin::INFO`], so the adapter holds no product's facts.
/// `source` names the declaration it was generated from, for the file's first
/// line.
///
/// Each setting is a `SEAM_PLUGIN_` variable. The VST3 categories are the
/// VST3 exporter's own. The codes are the plugin's
/// [`au_codes`](crate::PluginInfo::au_codes), which JUCE also derives its
/// VST3 class id from, so the adapter's build is a different plugin from
/// the native one.
///
/// # Panics
///
/// When two of `P`'s keys share the VST3 id JUCE derives from them
/// ([`juce_param_id`]), or one has an id JUCE gives a parameter of its own:
/// its bypass, its program list, and for a plugin that takes MIDI input, its
/// MIDI controllers. JUCE would list only one of them, silently in a release
/// build.
///
/// # Examples
///
/// ```
#[doc = include_str!("../../doc/gain.rs")]
/// use seam_host::cabi::juce_settings;
///
/// let cmake = juce_settings::<Gain>("examples/gain/src/lib.rs");
/// assert!(cmake.contains("set(SEAM_PLUGIN_NAME \"Gain\")"));
/// assert!(cmake.contains("set(SEAM_PLUGIN_CODE \"gain\")"));
/// ```
pub fn juce_settings<P: Plugin>(source: &str) -> String {
    check_juce_ids(P::PARAMS.iter().map(|decl| decl.key), P::INFO.midi_input);
    let info = &P::INFO;
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# The JUCE adapter's settings for {}.\n#\n# Generated by `cargo xtask gen` from {source}. Do not edit.\n",
        info.name
    );
    let mut text = |name: &str, value: &str| {
        let _ = writeln!(out, "set(SEAM_PLUGIN_{name} \"{}\")", quoted(value));
    };
    text("NAME", info.name);
    text("VENDOR", info.vendor);
    text("URL", info.url);
    text("EMAIL", info.email);
    text("DESCRIPTION", info.description);
    text("VERSION", info.version);
    text("ID", info.id);
    text("CODE", &code(info.au_codes.0));
    text("MANUFACTURER_CODE", &code(info.au_codes.1));
    let flag = |on: bool| if on { "TRUE" } else { "FALSE" };
    let _ = writeln!(
        out,
        "set(SEAM_PLUGIN_IS_SYNTH {})",
        flag(info.category == Category::Instrument)
    );
    let _ = writeln!(out, "set(SEAM_PLUGIN_MIDI_INPUT {})", flag(info.midi_input));
    let _ = writeln!(
        out,
        "set(SEAM_PLUGIN_MIDI_OUTPUT {})",
        flag(info.midi_output)
    );
    let categories: Vec<String> = info
        .vst3_categories()
        .into_iter()
        .map(|category| format!("\"{}\"", quoted(category)))
        .collect();
    let _ = writeln!(
        out,
        "set(SEAM_PLUGIN_VST3_CATEGORIES {})",
        categories.join(" ")
    );
    out
}

/// Returns the VST3 id JUCE's wrapper gives a parameter named by `key`.
///
/// The id is JUCE 9's `String::hashCode` over the key's characters, its top bit
/// cleared for Studio One (`VST3ClientExtensions::convertJuceParameterId`).
/// JUCE's id is not Seam's own, which only Seam's exporters give hosts.
///
/// # Examples
///
/// ```
/// use seam_host::cabi::juce_param_id;
///
/// let id = juce_param_id("gain");
/// assert_eq!(id & 0x8000_0000, 0, "the top bit is cleared, for Studio One");
/// assert_ne!(id, seam_params::host_id("gain"), "not the id Seam's own exporters give");
/// ```
pub fn juce_param_id(key: &str) -> u32 {
    key.chars().fold(0u32, |hash, character| {
        hash.wrapping_mul(31).wrapping_add(u32::from(character))
    }) & 0x7FFF_FFFF
}

/// Refuses keys whose JUCE ids collide with each other or with JUCE's own.
/// JUCE adds its MIDI controllers only for a plugin that takes MIDI input.
fn check_juce_ids<'a>(keys: impl Iterator<Item = &'a str>, midi_input: bool) {
    let mut taken: Vec<(RangeInclusive<u32>, &str)> = JUCE_RESERVED_IDS.to_vec();
    if midi_input {
        taken.push((
            JUCE_MIDI_CONTROLLER_IDS,
            "one of JUCE's MIDI controller parameters",
        ));
    }
    for key in keys {
        let id = juce_param_id(key);
        if let Some((_, other)) = taken.iter().find(|(ids, _)| ids.contains(&id)) {
            panic!("the key \"{key}\" has the JUCE id {id:#010x}, which {other} has too");
        }
        taken.push((id..=id, key));
    }
}

/// A four-character code as text. A byte that is not printable ASCII
/// becomes `?`, so the setting stays printable; JUCE takes any four
/// characters.
fn code(bytes: [u8; 4]) -> String {
    bytes
        .iter()
        .map(|&byte| {
            if byte.is_ascii_graphic() {
                char::from(byte)
            } else {
                '?'
            }
        })
        .collect()
}

/// `value` inside a quoted CMake argument, where a `;` is kept as it is.
fn quoted(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for character in value.chars() {
        match character {
            '\\' | '"' | '$' => {
                out.push('\\');
                out.push(character);
            }
            '\n' => out.push_str("\\n"),
            other => out.push(other),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::{check_juce_ids, code, juce_param_id, quoted};

    #[test]
    fn cmake_text_escapes_what_cmake_reads() {
        assert_eq!(quoted(r#"a "b" $c;d\e"#), r#"a \"b\" \$c;d\\e"#);
        assert_eq!(quoted("one\ntwo"), "one\\ntwo");
    }

    #[test]
    fn a_code_stays_printable() {
        assert_eq!(code(*b"SmEq"), "SmEq");
        assert_eq!(code([b'a', 0, b'b', 0x80]), "a?b?");
    }

    #[test]
    fn juce_ids_are_juces_hash_of_the_key() {
        // As JUCE's VST3 wrapper lists the example EQ's parameters, through
        // its hosting.
        assert_eq!(juce_param_id("hp.on"), 99_430_533);
        assert_eq!(juce_param_id("out.gain"), 8_795_679);
        // Its hash has the top bit set, which JUCE clears for Studio One.
        assert_eq!(juce_param_id("high.freq"), 1_408_935_748);
        assert_eq!(juce_param_id("éa"), (233 * 31 + 97) & 0x7FFF_FFFF);
    }

    #[test]
    fn colliding_juce_ids_are_refused() {
        // "Aa" and "BB" share Java's and JUCE's string hash.
        let refused = std::panic::catch_unwind(|| check_juce_ids(["Aa", "BB"].into_iter(), false));
        assert!(refused.is_err(), "two keys");
        // A key whose hash is 'byps', the bypass JUCE adds itself.
        let bypass = "\u{9711}\u{7f076}\u{12}\u{0}";
        assert_eq!(juce_param_id(bypass), 0x6279_7073);
        let reserved = std::panic::catch_unwind(|| check_juce_ids(std::iter::once(bypass), false));
        assert!(reserved.is_err(), "JUCE's own");
        check_juce_ids(["hp.on", "out.gain"].into_iter(), false);
    }

    #[test]
    fn a_midi_controllers_id_is_refused_when_juce_adds_them() {
        // The first and last ids of JUCE's MIDI controller parameters, and
        // the ids either side of them.
        let (first, last) = ("cc.bfgmpdl", "cc.bfgmrin");
        let (before, after) = ("cc.bfgmpdk", "cc.bfgmrio");
        assert_eq!(juce_param_id(first), 0x6d63_6d00);
        assert_eq!(juce_param_id(last), 0x6d63_6d00 + 16 * 130 - 1);
        assert_eq!(juce_param_id(before) + 1, juce_param_id(first));
        assert_eq!(juce_param_id(after), juce_param_id(last) + 1);
        let midi_input = true;
        for key in [first, last] {
            let refused =
                std::panic::catch_unwind(|| check_juce_ids(std::iter::once(key), midi_input));
            assert!(
                refused.is_err(),
                "{key}, for a plugin that takes MIDI input"
            );
            check_juce_ids(std::iter::once(key), !midi_input);
        }
        check_juce_ids([before, after].into_iter(), midi_input);
    }
}
