//! `seam.h`, written from the interface's own declarations.

use std::fmt::Write as _;

use super::abi::{self, CStruct};

/// Returns the C header for the interface, as `cargo xtask gen` commits it at
/// `crates/host/include/seam.h`.
///
/// It declares every constant, the opaque instance, every struct and the one
/// entry point. Each field's C declaration is spelled from its Rust type, so a
/// change of type changes this text, which the drift gate catches. Then it
/// asserts each struct's size and each field's offset as Rust laid them out. A
/// C or C++ build against a header whose layout no longer matches the library
/// then fails to compile rather than misread memory. The layout is the one for
/// the generating target's pointer width, the same on every target of that
/// width; the committed header is the 64-bit one.
///
/// # Examples
///
/// ```
/// let header = seam_host::cabi::header();
/// assert!(header.contains("#define SEAM_ABI_VERSION 1u"));
/// assert!(header.contains("const SeamPlugin* seam_plugin(void);"));
/// ```
pub fn header() -> String {
    let mut out = String::new();
    out.push_str(PREAMBLE);
    for constant in abi::consts() {
        comment(&mut out, "", constant.doc);
        let _ = writeln!(out, "#define {} {}u", constant.name, constant.value);
        out.push('\n');
    }
    out.push_str("// One instance of the plugin.\n");
    out.push_str("typedef struct SeamInstance SeamInstance;\n\n");
    let structs = abi::structs();
    for item in &structs {
        declare(&mut out, item);
    }
    out.push_str(ENTRY);
    let bits = usize::BITS;
    let _ = writeln!(
        out,
        "\n// Each layout as Rust computed it, the same on every {bits}-bit target."
    );
    let _ = writeln!(out, "#if UINTPTR_MAX == UINT{bits}_MAX");
    out.push_str("#ifdef __cplusplus\n");
    out.push_str("#define SEAM_LAYOUT(condition) static_assert(condition, #condition)\n");
    out.push_str("#else\n");
    out.push_str("#define SEAM_LAYOUT(condition) _Static_assert(condition, #condition)\n");
    out.push_str("#endif\n");
    for item in &structs {
        let _ = writeln!(out, "SEAM_LAYOUT(sizeof({}) == {});", item.name, item.size);
        for field in &item.fields {
            let _ = writeln!(
                out,
                "SEAM_LAYOUT(offsetof({}, {}) == {});",
                item.name, field.name, field.offset
            );
        }
    }
    out.push_str("#undef SEAM_LAYOUT\n#else\n");
    let _ = writeln!(
        out,
        "#error \"this seam.h asserts the layout of a {}-bit target\"",
        usize::BITS
    );
    out.push_str("#endif\n\n#endif // SEAM_H\n");
    out
}

/// A struct's declaration.
fn declare(out: &mut String, item: &CStruct) {
    comment(out, "", item.doc);
    let _ = writeln!(out, "typedef struct {} {{", item.name);
    for field in &item.fields {
        comment(out, "    ", field.doc);
        let _ = writeln!(out, "    {};", field.declaration);
    }
    let _ = writeln!(out, "}} {};\n", item.name);
}

/// Doc lines as `//` comments, up to the `# Examples` section, which is
/// Rust's alone.
fn comment(out: &mut String, indent: &str, lines: &[&str]) {
    let end = lines
        .iter()
        .position(|line| line.trim() == "# Examples")
        .unwrap_or(lines.len());
    let mut lines = &lines[..end];
    while let [rest @ .., last] = lines
        && last.trim().is_empty()
    {
        lines = rest;
    }
    for line in lines {
        let line = line.strip_prefix(' ').unwrap_or(line);
        if line.is_empty() {
            let _ = writeln!(out, "{indent}//");
        } else {
            let _ = writeln!(out, "{indent}// {line}");
        }
    }
}

const PREAMBLE: &str = "\
// seam.h: the C interface a Seam plugin exports, for the JUCE adapter.
//
// Generated by `cargo xtask gen` from crates/host/src/cabi. Do not edit.
//
// A plugin built with `seam_host::export_cabi!` as a static library exports
// one symbol, `seam_plugin`, which answers the table below: the plugin's
// facts and every call into an instance. The header and the library are
// built from one commit; the adapter checks SEAM_ABI_VERSION all the same.
//
// Threads: each call says where it may run, and `SeamPlugin` below says
// which thread a call marked \"main thread\" runs on. No call unwinds into
// the caller, and no callback the caller passes may unwind into the plugin.
//
// Pointers, which the plugin relies on and does not check beyond null:
// - An instance passed to a call is null or one `create` answered that
//   `destroy` has not freed. No other call into it runs during its
//   `destroy`, except the `idle` whose host callback makes that `destroy`.
// - A pointer a call writes its answer through (`layout`, `info`,
//   `normalized`) is null or valid for writing one of its type until the
//   call returns. `text`'s buffer is null or valid for writing `capacity`
//   bytes.
// - A `SeamStr` the caller passes, and `load`'s `data`, are valid for
//   reading their length until the call returns. A `SeamStr` the plugin
//   answers points into its own declarations and stays valid while it is
//   loaded.
// - In a `SeamProcess`, each channel list is null or holds its count of
//   channels. Each channel is null or valid for `frames` floats until
//   `process` returns, for writing too among the outputs. Nothing else
//   reads or writes them meanwhile. Any two channels, in either list, are
//   one buffer or share no float: an output may be an input's buffer, as
//   in place.
// - A `SeamHost`'s callbacks and context stay valid until `destroy`
//   returns; `save`'s writer and its context, until `save` returns.
//
// The header needs C11 or C++11, for the layout assertions at the end.

#ifndef SEAM_H
#define SEAM_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#ifdef __cplusplus
extern \"C\" {
#endif

";

const ENTRY: &str = "\
// The plugin's table, valid while the library is loaded. Any thread.
const SeamPlugin* seam_plugin(void);

#ifdef __cplusplus
}
#endif
";
